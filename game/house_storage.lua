function Storage.interior(index,location)
    index=math.floor(tonumber(index) or 1)
    if index>=6 and index<=255 then return index end
    return 5+(math.max(1,math.min(50,tonumber(location) or 1))-1)*5+((index-1)%5+1)
end

function Storage.definition(index,location)
    index=Storage.interior(index,location)
    local stop=math.floor((index-6)/5)+1
    local variant=(index-6)%5+1
    local point=anchors[stop][variant]
    return {id="built-in-storage",filename=string.format("stop%02d-interior-%02d.png",stop,variant),
        x=Storage.DRAW_X+point[1]*Storage.DRAW_W,y=Storage.DRAW_Y+point[2]*Storage.DRAW_H,
        u=point[1],v=point[2],label="HOUSE STORAGE"}
end

function Storage.place(item,index,location,compartment)
    local spot=Storage.definition(index,location)
    local number=compartment or 1
    item.name="house-storage"
    item.x=spot.x+(number-1)*18
    item.y=spot.y
    item.houseStorageHotspot=true; item.permanent=true
    item.houseStorageId=spot.id..":"..number
    item.storageLabel=number==1 and spot.label or (spot.label.." "..number)
    item.generatedFurniture=nil; item.scale=nil; item.rotation=nil
    item.storage=item.storage or {}; item.layer=1
    return item
end

Storage.anchors=anchors
